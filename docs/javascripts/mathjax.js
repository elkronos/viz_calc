window.MathJax = {
  tex: {
    inlineMath: [["\\(", "\\)"]],
    displayMath: [["\\[", "\\]"]],
    processEscapes: true,
    processEnvironments: true
  },
  options: {
    ignoreHtmlClass: ".*|",
    processHtmlClass: "arithmatex"
  }
};

// Only a page with math loads the MathJax bundle, which typesets the page once it has loaded.
document$.subscribe(() => {
  if (!document.querySelector(".arithmatex")) return;
  if (window.MathJax.typesetPromise) {
    MathJax.startup.output.clearCache();
    MathJax.typesetClear();
    MathJax.texReset();
    MathJax.typesetPromise();
  } else if (!document.getElementById("mathjax-bundle")) {
    const script = document.createElement("script");
    script.id = "mathjax-bundle";
    script.src = "https://cdn.jsdelivr.net/npm/mathjax@3/es5/tex-mml-chtml.js";
    script.async = true;
    document.head.appendChild(script);
  }
});
